let currentLang = localStorage.getItem('academy_lang') || 'ar';

function t(key) {
    return i18n[currentLang][key] || key;
}

function setLanguage(lang) {
    if (lang !== 'ar' && lang !== 'en') return;
    currentLang = lang;
    localStorage.setItem('academy_lang', lang);
    updateUI();
}

function toggleLanguage() {
    setLanguage(currentLang === 'ar' ? 'en' : 'ar');
}

function updateUI() {
    // Update HTML direction and lang attribute
    document.documentElement.lang = currentLang;
    document.documentElement.dir = currentLang === 'ar' ? 'rtl' : 'ltr';

    // Update all elements with data-i18n attribute
    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.dataset.i18n;
        element.textContent = t(key);
    });

    // Update input/textarea placeholders marked with data-placeholder="<i18n key>"
    document.querySelectorAll('[data-placeholder]').forEach(element => {
        element.placeholder = t(element.dataset.placeholder);
    });

    // Update specific button text if needed
    const langBtn = document.getElementById('lang-toggle');
    if (langBtn) langBtn.textContent = t('language_btn');
}

// Initial update on load
document.addEventListener('DOMContentLoaded', () => {
    updateUI();
});
